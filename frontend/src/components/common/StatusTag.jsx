// Small status chip using the four implementation terms. Use one per section (not per sentence).
export const STATUS = {
  simulated: {
    label: 'Simulated',
    meaning: 'Behaviour generated by frontend logic in the browser, without a connected real-world system.',
    className: 'bg-primary-container/15 text-primary border-primary/30',
  },
  illustrative: {
    label: 'Illustrative',
    meaning: 'Sample values or visuals that are not experimental results.',
    className: 'bg-secondary-container/30 text-secondary-fixed border-secondary/30',
  },
  planned: {
    label: 'Planned',
    meaning: 'Functionality intended for future implementation and not currently available.',
    className: 'bg-tertiary-container/20 text-tertiary border-tertiary/30',
  },
  'not-implemented': {
    label: 'Not implemented',
    meaning: 'Functionality that does not currently exist in the application.',
    className: 'bg-surface-container-highest text-on-surface border-outline-variant',
  },
};

// Visible text is "<Label>" or "<Label>: <detail>", so the meaning never depends on colour alone.
export default function StatusTag({ kind, children, className = '' }) {
  const s = STATUS[kind];
  return (
    <span
      title={s.meaning}
      className={`inline-flex items-center px-2 py-0.5 rounded-full border text-[10px] font-semibold uppercase tracking-wider whitespace-nowrap ${s.className} ${className}`}
    >
      {children ? `${s.label}: ${children}` : s.label}
    </span>
  );
}
